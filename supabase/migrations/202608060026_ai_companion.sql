create table public.ai_companion_profiles (
  user_id bigint primary key references public.users(id) on delete cascade,
  character_id text check (character_id in ('chiikawa', 'hachiware', 'usagi')),
  memory_summary text not null default '' check (char_length(memory_summary) <= 1000),
  consented_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.ai_conversations (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  character_id text not null check (character_id in ('chiikawa', 'hachiware', 'usagi')),
  mode text not null check (mode in ('GENERAL', 'MISSION')),
  mission_id text references public.ai_missions(id) on delete restrict,
  status text not null default 'ACTIVE' check (status in ('ACTIVE', 'PAUSED', 'COMPLETED')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint ai_conversations_mission_mode check ((mode = 'MISSION') = (mission_id is not null))
);

create unique index ai_conversations_one_active on public.ai_conversations(user_id) where status = 'ACTIVE';
create index ai_conversations_user_recent on public.ai_conversations(user_id, updated_at desc);

create table public.ai_mission_progress (
