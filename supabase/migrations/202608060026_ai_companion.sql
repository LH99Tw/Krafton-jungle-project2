  conversation_id bigint references public.ai_conversations(id) on delete set null,
  status text not null default 'ACTIVE' check (status in ('ACTIVE', 'PAUSED', 'COMPLETED')),
  reward_points bigint not null,
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  updated_at timestamptz not null default now(),
  unique (user_id, mission_id)
);

create unique index ai_mission_progress_one_active on public.ai_mission_progress(user_id) where status = 'ACTIVE';

create table public.ai_daily_user_usage (
  user_id bigint not null references public.users(id) on delete cascade,
  usage_date date not null,
  turn_count integer not null default 0 check (turn_count between 0 and 20),
  updated_at timestamptz not null default now(),
  primary key (user_id, usage_date)
);

create table public.ai_daily_global_usage (
