drop function if exists public.read_post(bigint, bigint);
drop view if exists public.post_details;

create view public.post_details
with (security_invoker = true)
as
select
  p.id,
  p.blog_id,
  p.category_id,
  c.name as category_name,
  p.title,
  p.content,
  p.status,
  p.view_count,
  p.published_at,
  p.created_at,
  p.updated_at,
  p.deleted_at,
  p.purge_after,
  b.name as blog_name,
  b.slug as blog_slug,
  b.owner_id,
  u.nickname as author_nickname
from public.posts p
join public.blogs b on b.id = p.blog_id
join public.users u on u.id = b.owner_id
left join public.blog_categories c on c.id = p.category_id;

revoke all on public.post_details from public, anon, authenticated;
grant select on public.post_details to service_role;

create or replace function public.read_post(p_post_id bigint, p_request_user_id bigint default null)
returns setof public.post_details
language plpgsql
security definer
set search_path = public
as $$
declare
  target public.post_details%rowtype;
begin
  select * into target from public.post_details where id = p_post_id and deleted_at is null;
  if not found then return; end if;
  if target.status = 'DRAFT' and target.owner_id is distinct from p_request_user_id then return; end if;
  if target.status = 'PUBLISHED' then
    update public.posts set view_count = view_count + 1 where id = p_post_id;
    target.view_count := target.view_count + 1;
  end if;
  return next target;
end;
$$;

revoke all on function public.read_post(bigint, bigint) from public, anon, authenticated;
grant execute on function public.read_post(bigint, bigint) to service_role;

