create or replace function public.purge_blog_trash()
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  delete from public.posts where purge_after is not null and purge_after <= now();

  delete from public.market_items mi
  where mi.purge_after is not null and mi.purge_after <= now()
    and not exists (select 1 from public.market_conversations mc where mc.item_id = mi.id);

  update public.market_items mi set
    title = '[삭제된 상품]', description = '삭제된 상품입니다.', category = '삭제됨', tags = '{}',
    purge_after = null, updated_at = now()
  where mi.purge_after is not null and mi.purge_after <= now()
    and exists (select 1 from public.market_conversations mc where mc.item_id = mi.id);
end;
$$;

revoke all on function public.purge_blog_trash() from public, anon, authenticated;
grant execute on function public.purge_blog_trash() to service_role;

do $$
begin
  if to_regclass('cron.job') is not null then
    execute $cron$select cron.schedule('purge-blog-trash-daily', '17 3 * * *', 'select public.purge_blog_trash()')
      where not exists (select 1 from cron.job where jobname = 'purge-blog-trash-daily')$cron$;
  end if;
end $$;
