create table if not exists public.blog_categories (
  id bigint generated by default as identity primary key,
  blog_id bigint not null references public.blogs(id) on delete restrict,
  name text not null,
  normalized_name text not null,
  position integer not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint blog_categories_name_length check (char_length(name) between 1 and 30),
  constraint blog_categories_position_nonnegative check (position >= 0),
  unique (blog_id, normalized_name),
  unique (blog_id, position)
);

create index if not exists blog_categories_blog_idx on public.blog_categories (blog_id, position);
