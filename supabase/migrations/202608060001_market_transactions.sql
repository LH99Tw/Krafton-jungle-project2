create table if not exists public.wallets (
  user_id bigint primary key references public.users(id) on delete cascade,
  balance bigint not null default 0 check (balance >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.market_orders (
  id bigint generated by default as identity primary key,
  item_id bigint not null unique references public.market_items(id) on delete restrict,
  buyer_id bigint not null references public.users(id) on delete restrict,
  seller_id bigint not null references public.users(id) on delete restrict,
  price_points bigint not null check (price_points > 0),
  status text not null default 'PAID' check (status in ('PAID', 'COMPLETED', 'CANCELLED')),
  paid_at timestamptz not null default now(),
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint market_orders_participants check (buyer_id <> seller_id)
);

create table if not exists public.wallet_transactions (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  order_id bigint references public.market_orders(id) on delete restrict,
  type text not null check (type in ('INITIAL_GRANT', 'POINT_CHARGE', 'MARKET_PURCHASE', 'MARKET_SALE', 'REFUND')),
  amount bigint not null check (amount <> 0),
  balance_after bigint not null check (balance_after >= 0),
  created_at timestamptz not null default now()
);

create unique index if not exists wallet_initial_grant_unique
  on public.wallet_transactions (user_id) where type = 'INITIAL_GRANT';
create index if not exists market_orders_buyer_idx on public.market_orders (buyer_id, created_at desc);
create index if not exists market_orders_seller_idx on public.market_orders (seller_id, created_at desc);
create index if not exists wallet_transactions_user_idx on public.wallet_transactions (user_id, created_at desc);

insert into public.wallets (user_id, balance)
select id, 100000 from public.users
on conflict (user_id) do nothing;

insert into public.wallet_transactions (user_id, type, amount, balance_after)
select user_id, 'INITIAL_GRANT', 100000, balance
from public.wallets
where balance >= 100000
on conflict do nothing;

create or replace function public.initialize_user_wallet()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.wallets (user_id, balance) values (new.id, 100000)
  on conflict (user_id) do nothing;
  insert into public.wallet_transactions (user_id, type, amount, balance_after)
  values (new.id, 'INITIAL_GRANT', 100000, 100000)
  on conflict do nothing;
  return new;
end;
$$;

