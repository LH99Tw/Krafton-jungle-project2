create or replace function public.purchase_market_item(p_item_id bigint, p_buyer_id bigint)
returns table(order_id bigint, buyer_balance bigint, seller_balance bigint)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_item public.market_items%rowtype;
  v_order_id bigint;
  v_buyer_balance bigint;
  v_seller_balance bigint;
begin
  select * into v_item from public.market_items where id = p_item_id for update;
  if not found then raise exception 'ITEM_NOT_FOUND'; end if;
  if v_item.seller_id = p_buyer_id then raise exception 'SELF_PURCHASE_NOT_ALLOWED'; end if;
  if v_item.status <> 'SELLING' then raise exception 'ITEM_NOT_AVAILABLE'; end if;

  insert into public.wallets (user_id, balance) values (p_buyer_id, 0) on conflict do nothing;
  insert into public.wallets (user_id, balance) values (v_item.seller_id, 0) on conflict do nothing;
  select balance into v_buyer_balance from public.wallets where user_id = p_buyer_id for update;
  if v_buyer_balance < v_item.price_points then raise exception 'INSUFFICIENT_POINTS'; end if;

  update public.wallets set balance = balance - v_item.price_points, updated_at = now()
    where user_id = p_buyer_id returning balance into v_buyer_balance;
  update public.wallets set balance = balance + v_item.price_points, updated_at = now()
    where user_id = v_item.seller_id returning balance into v_seller_balance;
  insert into public.market_orders (item_id, buyer_id, seller_id, price_points)
    values (v_item.id, p_buyer_id, v_item.seller_id, v_item.price_points)
    returning id into v_order_id;
  update public.market_items set status = 'SOLD', updated_at = now() where id = v_item.id;
  insert into public.wallet_transactions (user_id, order_id, type, amount, balance_after) values
    (p_buyer_id, v_order_id, 'MARKET_PURCHASE', -v_item.price_points, v_buyer_balance),
    (v_item.seller_id, v_order_id, 'MARKET_SALE', v_item.price_points, v_seller_balance);
  return query select v_order_id, v_buyer_balance, v_seller_balance;
exception
  when unique_violation then raise exception 'ITEM_NOT_AVAILABLE';
end;
$$;

create or replace function public.complete_market_order(p_order_id bigint, p_buyer_id bigint)
returns public.market_orders
language plpgsql
security definer
set search_path = public
as $$
declare v_order public.market_orders%rowtype;
begin
  select * into v_order from public.market_orders where id = p_order_id for update;
  if not found then raise exception 'ORDER_NOT_FOUND'; end if;
  if v_order.buyer_id <> p_buyer_id then raise exception 'ORDER_FORBIDDEN'; end if;
  if v_order.status <> 'PAID' then raise exception 'ORDER_NOT_COMPLETABLE'; end if;
  update public.market_orders set status = 'COMPLETED', completed_at = now(), updated_at = now()
    where id = p_order_id returning * into v_order;
  return v_order;
end;
$$;

create or replace function public.charge_wallet_points(p_user_id bigint, p_amount bigint)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare v_balance bigint;
begin
  if p_amount not in (10000, 50000, 100000) then raise exception 'INVALID_CHARGE_AMOUNT'; end if;
  insert into public.wallets (user_id, balance) values (p_user_id, 0) on conflict do nothing;
  update public.wallets set balance = balance + p_amount, updated_at = now()
    where user_id = p_user_id returning balance into v_balance;
  insert into public.wallet_transactions (user_id, type, amount, balance_after)
    values (p_user_id, 'POINT_CHARGE', p_amount, v_balance);
  return v_balance;
end;
$$;

