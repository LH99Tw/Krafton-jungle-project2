alter table public.posts rename column category_id to legacy_classification_id;

create table public.post_classifications (
  post_id bigint not null references public.posts(id) on delete cascade,
  classification_id bigint not null references public.blog_classifications(id) on delete restrict,
  position smallint not null,
  created_at timestamptz not null default now(),
  primary key (post_id, classification_id),
  unique (post_id, position),
  constraint post_classifications_position check (position between 0 and 4)
);

insert into public.post_classifications (post_id, classification_id, position)
select id, legacy_classification_id, 0
from public.posts
where legacy_classification_id is not null
on conflict do nothing;

alter table public.posts drop column legacy_classification_id;

create table public.blog_categories (
  id bigint generated by default as identity primary key,
  blog_id bigint not null references public.blogs(id) on delete restrict,
  name text not null,
  normalized_name text not null,
  position integer not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint blog_categories_name_length check (char_length(name) between 1 and 30),
  constraint blog_categories_position_nonnegative check (position >= 0),
  unique (blog_id, normalized_name),
  unique (blog_id, position)
);

alter table public.posts add column category_id bigint references public.blog_categories(id) on delete restrict;

create index blog_categories_blog_idx_v2 on public.blog_categories (blog_id, position);
create index post_classifications_classification_idx on public.post_classifications (classification_id, post_id);

create table public.post_likes (
  user_id bigint not null references public.users(id) on delete cascade,
  post_id bigint not null references public.posts(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, post_id)
);

create table public.post_bookmarks (
  user_id bigint not null references public.users(id) on delete cascade,
  post_id bigint not null references public.posts(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, post_id)
);

create table public.post_comments (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.posts(id) on delete cascade,
  author_id bigint not null references public.users(id) on delete restrict,
  parent_id bigint references public.post_comments(id) on delete restrict,
  body text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  constraint post_comments_body_length check (char_length(body) between 1 and 1000)
);

create index post_likes_post_idx on public.post_likes (post_id);
create index post_bookmarks_post_idx on public.post_bookmarks (post_id);
create index post_comments_post_idx on public.post_comments (post_id, created_at, id);
create index post_comments_parent_idx on public.post_comments (parent_id) where parent_id is not null;

alter table public.users add column if not exists role text not null default 'USER';
