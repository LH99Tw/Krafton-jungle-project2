create table public.home_banners (
  id bigint generated by default as identity primary key,
  eyebrow text not null default 'NOTICE · EVENT',
  title text not null,
  description text not null default '',
  image_url text,
  cta_label text not null default '자세히 보기',
  cta_url text not null,
  starts_at timestamptz not null,
  ends_at timestamptz,
  position smallint not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint home_banners_title_length check (char_length(title) between 1 and 120),
  constraint home_banners_description_length check (char_length(description) <= 300),
  constraint home_banners_position check (position between 0 and 99),
  constraint home_banners_window check (ends_at is null or ends_at > starts_at)
