create or replace function public.notify_market_chat_change()
returns trigger
language plpgsql security definer set search_path = public
as $$
declare
  target_conversation_id bigint;
begin
  if tg_table_name = 'market_message_reactions' then
    select conversation_id into target_conversation_id
    from public.market_messages where id = case when tg_op = 'DELETE' then old.message_id else new.message_id end;
  elsif tg_table_name = 'market_messages' then
    target_conversation_id := case when tg_op = 'DELETE' then old.conversation_id else new.conversation_id end;
  else
    target_conversation_id := case when tg_op = 'DELETE' then old.id else new.id end;
  end if;

  insert into public.market_chat_versions(id, version, updated_at)
  values (true, 1, clock_timestamp())
  on conflict (id) do update
    set version = public.market_chat_versions.version + 1, updated_at = excluded.updated_at;

  if to_regprocedure('realtime.send(jsonb,text,text,boolean)') is not null then
    execute 'select realtime.send($1, $2, $3, $4)'
      using jsonb_build_object('conversationId', target_conversation_id), 'changed', 'market-chat', false;
  end if;
  return null;
end;
$$;

drop trigger if exists market_messages_realtime_change on public.market_messages;
create trigger market_messages_realtime_change
after insert or update of read_at, deleted_at on public.market_messages
for each row execute function public.notify_market_chat_change();

drop trigger if exists market_message_reactions_realtime_change on public.market_message_reactions;
create trigger market_message_reactions_realtime_change
after insert or delete on public.market_message_reactions
for each row execute function public.notify_market_chat_change();
